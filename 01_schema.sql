CREATE TABLE departments (
    department_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE employees (
    employee_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_number VARCHAR2(30) NOT NULL UNIQUE,
    login_name VARCHAR2(128) UNIQUE,
    first_name VARCHAR2(80) NOT NULL,
    last_name VARCHAR2(80) NOT NULL,
    email VARCHAR2(254) NOT NULL UNIQUE,
    phone VARCHAR2(30),
    department_id NUMBER NOT NULL REFERENCES departments(department_id),
    job_title VARCHAR2(100) NOT NULL,
    manager_id NUMBER REFERENCES employees(employee_id),
    hire_date DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    monthly_salary NUMBER(12, 2) NOT NULL CHECK (monthly_salary >= 0),
    employment_status VARCHAR2(12) DEFAULT 'ACTIVE' NOT NULL
        CHECK (employment_status IN ('ACTIVE', 'TERMINATED')),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE app_user_roles (
    username VARCHAR2(128) NOT NULL,
    role_code VARCHAR2(20) NOT NULL
        CHECK (role_code IN ('HR_ADMIN', 'EMPLOYEE', 'MANAGER', 'PAYROLL')),
    granted_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT app_user_roles_pk PRIMARY KEY (username, role_code)
);

CREATE TABLE attendance (
    attendance_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id NUMBER NOT NULL REFERENCES employees(employee_id),
    work_date DATE NOT NULL,
    check_in DATE,
    check_out DATE,
    CONSTRAINT attendance_employee_day_uq UNIQUE (employee_id, work_date),
    CONSTRAINT attendance_date_ck CHECK (work_date = TRUNC(work_date)),
    CONSTRAINT attendance_times_ck CHECK (
        check_out IS NULL OR (check_in IS NOT NULL AND check_out > check_in)
    )
);

CREATE TABLE leave_requests (
    leave_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id NUMBER NOT NULL REFERENCES employees(employee_id),
    leave_type VARCHAR2(30) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    is_paid CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_paid IN ('Y', 'N')),
    request_status VARCHAR2(12) DEFAULT 'PENDING' NOT NULL
        CHECK (request_status IN ('PENDING', 'APPROVED', 'REJECTED')),
    requested_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    reviewed_by VARCHAR2(128),
    reviewed_at TIMESTAMP,
    CONSTRAINT leave_dates_ck CHECK (
        start_date = TRUNC(start_date)
        AND end_date = TRUNC(end_date)
        AND end_date >= start_date
    )
);

CREATE TABLE payroll_runs (
    payroll_run_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_start DATE NOT NULL UNIQUE,
    run_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    run_by VARCHAR2(128) NOT NULL,
    CONSTRAINT payroll_period_ck CHECK (
        period_start = TRUNC(period_start, 'MM')
    )
);

CREATE TABLE payroll_adjustments (
    adjustment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id NUMBER NOT NULL REFERENCES employees(employee_id),
    period_start DATE NOT NULL,
    adjustment_type VARCHAR2(10) NOT NULL
        CHECK (adjustment_type IN ('BONUS', 'DEDUCTION')),
    amount NUMBER(12, 2) NOT NULL CHECK (amount > 0),
    description VARCHAR2(500),
    created_by VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT adjustment_period_ck CHECK (
        period_start = TRUNC(period_start, 'MM')
    )
);

CREATE TABLE payroll_items (
    payroll_run_id NUMBER NOT NULL REFERENCES payroll_runs(payroll_run_id),
    employee_id NUMBER NOT NULL REFERENCES employees(employee_id),
    eligible_days NUMBER(3) NOT NULL,
    working_days NUMBER(3) NOT NULL,
    base_pay NUMBER(12, 2) NOT NULL,
    overtime_pay NUMBER(12, 2) NOT NULL,
    bonus_amount NUMBER(12, 2) NOT NULL,
    deduction_amount NUMBER(12, 2) NOT NULL,
    net_pay NUMBER(12, 2) NOT NULL,
    CONSTRAINT payroll_items_pk PRIMARY KEY (payroll_run_id, employee_id),
    CONSTRAINT payroll_days_ck CHECK (
        eligible_days >= 0 AND working_days >= 0 AND eligible_days <= working_days
    ),
    CONSTRAINT payroll_amounts_ck CHECK (
        base_pay >= 0 AND overtime_pay >= 0 AND bonus_amount >= 0
        AND deduction_amount >= 0 AND net_pay >= 0
    )
);

CREATE TABLE salary_advances (
    advance_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id NUMBER NOT NULL REFERENCES employees(employee_id),
    amount NUMBER(12, 2) NOT NULL CHECK (amount > 0),
    deduction_period DATE NOT NULL,
    request_status VARCHAR2(12) DEFAULT 'PENDING' NOT NULL
        CHECK (request_status IN ('PENDING', 'APPROVED', 'REJECTED', 'SETTLED')),
    requested_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    reviewed_by VARCHAR2(128),
    reviewed_at TIMESTAMP,
    payroll_run_id NUMBER REFERENCES payroll_runs(payroll_run_id),
    CONSTRAINT advance_period_ck CHECK (
        deduction_period = TRUNC(deduction_period, 'MM')
    )
);

CREATE TABLE performance_reviews (
    review_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id NUMBER NOT NULL REFERENCES employees(employee_id),
    reviewer_id NUMBER NOT NULL REFERENCES employees(employee_id),
    review_date DATE NOT NULL,
    review_status VARCHAR2(12) DEFAULT 'SCHEDULED' NOT NULL
        CHECK (review_status IN ('SCHEDULED', 'COMPLETED')),
    rating NUMBER(2, 1),
    feedback VARCHAR2(2000),
    completed_at TIMESTAMP,
    CONSTRAINT review_date_ck CHECK (review_date = TRUNC(review_date)),
    CONSTRAINT review_rating_ck CHECK (
        rating IS NULL OR rating BETWEEN 1 AND 5
    ),
    CONSTRAINT review_completion_ck CHECK (
        (review_status = 'SCHEDULED' AND rating IS NULL AND completed_at IS NULL)
        OR
        (review_status = 'COMPLETED' AND rating IS NOT NULL AND completed_at IS NOT NULL)
    )
);

CREATE INDEX attendance_work_date_ix ON attendance(work_date);
CREATE INDEX leave_employee_dates_ix ON leave_requests(employee_id, start_date, end_date);
CREATE INDEX payroll_adjustment_period_ix ON payroll_adjustments(period_start, employee_id);
CREATE INDEX performance_review_date_ix ON performance_reviews(review_date, employee_id);

CREATE OR REPLACE VIEW employee_directory AS
SELECT e.employee_id,
       e.employee_number,
       e.first_name,
       e.last_name,
       e.email,
       e.phone,
       e.department_id,
       d.department_name,
       e.job_title,
       e.manager_id,
       e.hire_date,
       e.employment_status
FROM employees e
JOIN departments d ON d.department_id = e.department_id;

CREATE OR REPLACE VIEW attendance_summary AS
SELECT employee_id,
       TRUNC(work_date, 'MM') AS period_start,
       COUNT(*) AS recorded_days,
       SUM(CASE WHEN check_out IS NOT NULL
                THEN ROUND((check_out - check_in) * 24, 2)
                ELSE 0 END) AS total_working_hours,
       SUM(CASE WHEN check_out IS NOT NULL
                THEN ROUND(GREATEST((check_out - check_in) * 24 - 8, 0), 2)
                ELSE 0 END) AS overtime_hours
FROM attendance
GROUP BY employee_id, TRUNC(work_date, 'MM');
